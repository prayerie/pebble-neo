static int get_rokuyo(int y, int m, int d) {
    d+=1;

    if (m < 3) { y--; m += 12; }
    int jdn = (1461 * y) >> 2;
    jdn += y / 400 - y / 100;
    jdn += (979 * (m - 2)) >> 5;
    jdn += 1721088 + d;

    if (jdn < RK_START_JDN || jdn > RK_END_JDN) return -1;

    int day_offset = jdn - RK_START_JDN - RK_FIRST_MONTH_OFFSET;

    int lo = 0, hi = RK_NUM_MONTHS - 1;
    while (lo < hi) {
        int mid = (lo + hi + 1) >> 1;
        if (RKCMDAYS[mid] <= day_offset) lo = mid;
        else hi = mid - 1;
    }
    int month_idx = lo;
    int day_in_month = day_offset - RKCMDAYS[month_idx] + 1;

    uint8_t packed = RK_MONTHS[month_idx >> 1];
    int nibble = (month_idx & 1) ? (packed & 0xF) : (packed >> 4);
    int phase = nibble & 0x7;

    return (phase + day_in_month - 1) % 6;
}